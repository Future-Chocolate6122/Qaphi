package install

// Unit devuelve la unit de systemd de Qaphi. Es la única fuente: el
// instalador la escribe y deploy/qaphi.service es una copia de referencia
// (un test comprueba que coinciden).
func Unit() string {
	return `# Generated by 'qaphi install'. It is regenerated on every update.
[Unit]
Description=Qaphi service monitor
After=network-online.target time-sync.target
Wants=network-online.target

[Service]
Type=simple
User=` + UserName + `
Group=` + UserName + `
EnvironmentFile=` + EnvPath + `
ExecStart=` + BinPath + ` serve
Restart=on-failure
RestartSec=5s
TimeoutStopSec=30s

# Data in /var/lib/qaphi, only accessible to the service user.
StateDirectory=qaphi
StateDirectoryMode=0700
ReadWritePaths=` + DataDir + `
UMask=0077

# ICMP ping without any other privilege.
AmbientCapabilities=CAP_NET_RAW
CapabilityBoundingSet=CAP_NET_RAW

# Hardening.
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK
SystemCallArchitectures=native

[Install]
WantedBy=multi-user.target
`
}
